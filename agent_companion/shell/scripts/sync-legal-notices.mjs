import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Copy the licence and third-party notices into the shell so a build can show
 * them.
 *
 * Both files live at the repository root, which a Vite build cannot import
 * from. Leaving them there meant the notices existed only for people who had
 * cloned the repository -- and the Live2D sample-data terms require the
 * copyright notice to travel with the product, not with its source.
 */

const shellRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(shellRoot, '..', '..')
const targetRoot = join(shellRoot, 'src', 'generated')

const files = [
  { source: join(repoRoot, 'LICENSE'), target: join(targetRoot, 'LICENSE.txt') },
  {
    source: join(repoRoot, 'docs', 'THIRD_PARTY_NOTICES.md'),
    target: join(targetRoot, 'THIRD_PARTY_NOTICES.md'),
  },
]

const missing = files.filter(({ source }) => !existsSync(source))
if (missing.length) {
  throw new Error(
    `Cannot ship legal notices: missing ${missing.map(({ source }) => source).join(', ')}`,
  )
}

mkdirSync(targetRoot, { recursive: true })

let copied = 0
for (const { source, target } of files) {
  const text = readFileSync(source, 'utf8')
  if (existsSync(target) && readFileSync(target, 'utf8') === text) continue
  copyFileSync(source, target)
  copied += 1
}

// A generated directory that is not tracked still has to be safe to import, so
// it carries its own note about where its contents come from.
writeFileSync(
  join(targetRoot, 'README.md'),
  '<!-- Generated by scripts/sync-legal-notices.mjs. Edit the sources at the repository root. -->\n',
)

console.log(copied ? `Synced ${copied} legal notice files.` : 'Legal notices are already in sync.')
